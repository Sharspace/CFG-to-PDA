import { CFG, PDA, SimulationResult } from '../types/grammar';

export function exportPDAToLaTeX(pda: PDA, cfg: CFG): string {
  const transitionsLatex = pda.transitions.map(t => {
    const inputLatex = t.inputSymbol === 'ε' ? '\\varepsilon' : t.inputSymbol;
    const stackTopLatex = t.stackTop;
    const replacementLatex = t.rawReplacement === 'ε' ? '\\varepsilon' : t.rawReplacement;
    return `    \\delta(q_0, ${inputLatex}, ${stackTopLatex}) &\\ni (q_0, ${replacementLatex}) && \\text{${t.type === 'expansion' ? 'Rule Expansion' : 'Terminal Matching'}} \\\\`;
  }).join('\n');

  return `% ============================================================
% Formal Single-State Pushdown Automaton (Empty-Stack Acceptance)
% Generated by Universal CFG to PDA Converter
% ============================================================

\\documentclass{article}
\\usepackage{amsmath, amssymb, amsthm}
\\usepackage{booktabs}

\\begin{document}

\\section*{Context-Free Grammar $G$}
The context-free grammar is defined as $G = (V, \\Sigma, R, S)$ where:
\\begin{itemize}
    \\item $V = \\{ ${cfg.nonTerminals.join(', ')} \\}$ (Non-terminals)
    \\item $\\Sigma = \\{ ${cfg.terminals.join(', ')} \\}$ (Terminals)
    \\item $S = ${cfg.startSymbol}$ (Start symbol)
\\end{itemize}

\\subsection*{Production Rules ($R$)}
\\begin{align*}
${cfg.productions.map(p => `    ${p.lhs} &\\to ${p.rawRhs === 'ε' ? '\\varepsilon' : p.rawRhs}`).join(' \\\\\n')}
\\end{align*}

\\section*{Equivalent Single-State PDA $M$}
The equivalent Pushdown Automaton accepting by empty stack is formally defined as:
\\[
M = (Q, \\Sigma, \\Gamma, \\delta, q_0, Z_0)
\\]
where:
\\begin{itemize}
    \\item $Q = \\{ q_0 \\}$ (Exactly one state)
    \\item $\\Sigma = \\{ ${pda.inputAlphabet.join(', ')} \\}$
    \\item $\\Gamma = V \\cup \\Sigma = \\{ ${pda.stackAlphabet.join(', ')} \\}$
    \\item $q_0 = q_0$ (Start state)
    \\item $Z_0 = ${pda.initialStackSymbol}$ (Initial stack symbol)
    \\item Acceptance criteria: $N(M) = \\{ w \\in \\Sigma^* \\mid (q_0, w, ${pda.initialStackSymbol}) \\vdash^* (q_0, \\varepsilon, \\varepsilon) \\}$
\\end{itemize}

\\subsection*{Transition Function $\\delta$}
\\begin{align*}
${transitionsLatex}
\\end{align*}

\\end{document}
`;
}

export function exportPDAToJSON(pda: PDA, cfg: CFG): string {
  return JSON.stringify(
    {
      grammar: {
        nonTerminals: cfg.nonTerminals,
        terminals: cfg.terminals,
        startSymbol: cfg.startSymbol,
        productions: cfg.productions.map(p => ({
          ruleNumber: p.ruleNumber,
          lhs: p.lhs,
          rhs: p.rhs,
          rawRhs: p.rawRhs,
          isEpsilon: p.isEpsilon,
        })),
        properties: cfg.properties,
      },
      pda: {
        states: pda.states,
        inputAlphabet: pda.inputAlphabet,
        stackAlphabet: pda.stackAlphabet,
        startState: pda.startState,
        initialStackSymbol: pda.initialStackSymbol,
        acceptance: pda.acceptance,
        transitions: pda.transitions.map(t => ({
          index: t.index,
          type: t.type,
          fromState: t.fromState,
          inputSymbol: t.inputSymbol,
          stackTop: t.stackTop,
          toState: t.toState,
          stackReplacement: t.stackReplacement,
          rawReplacement: t.rawReplacement,
          formalNotation: t.formalNotation,
          explanation: t.explanation,
        })),
      },
      timestamp: new Date().toISOString(),
    },
    null,
    2
  );
}

export function exportPDAToCSV(pda: PDA): string {
  const headers = ['#', 'Type', 'Current State', 'Input Symbol', 'Stack Top', 'Next State', 'Stack Replacement', 'Formal Transition', 'Explanation'];
  const rows = pda.transitions.map(t => [
    t.index,
    t.type === 'expansion' ? 'Non-Terminal Expansion' : 'Terminal Matching',
    t.fromState,
    t.inputSymbol,
    t.stackTop,
    t.toState,
    t.rawReplacement,
    `"${t.formalNotation}"`,
    `"${t.explanation.replace(/"/g, '""')}"`,
  ]);

  return [headers.join(','), ...rows.map(r => r.join(','))].join('\n');
}

export function exportSimulationTraceText(result: SimulationResult): string {
  const lines: string[] = [
    `=== PDA Simulation Trace ===`,
    `Input String: "${result.inputString}"`,
    `Tokenized: [${result.inputTokens.join(', ')}]`,
    `Verdict: ${result.isAccepted ? 'ACCEPTED' : 'REJECTED'}`,
    `Details: ${result.verdictMessage}`,
    `Total Configurations Explored: ${result.totalStepsExplored}`,
    `Max Stack Depth: ${result.maxStackDepth}`,
    ``,
    `--- Step-by-Step Execution Sequence ---`,
  ];

  result.executionPath.forEach((step, i) => {
    lines.push(
      `Step ${i}: State=${step.state} | Remaining Input=[${step.remainingInput.join(' ')}] | Stack=[${step.stack.join(' ')}]`
    );
    lines.push(`   Action: ${step.actionDescription}`);
    if (step.transitionApplied) {
      lines.push(`   Rule: ${step.transitionApplied.formalNotation}`);
    }
  });

  if (result.derivationSequence && result.derivationSequence.length > 0) {
    lines.push(``);
    lines.push(`--- Corresponding Leftmost Derivation (S =>* w) ---`);
    lines.push(result.derivationSequence.join(' => \n'));
  }

  return lines.join('\n');
}

export function downloadFile(filename: string, content: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
